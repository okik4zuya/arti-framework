"""SQLite-backed store for a single paper project's bibliography -- Layer 2
(`literature\\library.md`, canonical) and Layer 3 (`writing\\references.md`,
generated per-draft reference list) of ARTi-writing's Reference System. Unlike
`tools/arti-db` (a cross-project singleton under `~/.arti`), this tool is
per-project: it resolves its data file relative to `--project` (default cwd),
since bibliography data belongs to one paper project, not the framework as a
whole. One connection per call, guarded by a module-level lock, no ORM, no pip
deps. Every write auto-regenerates `literature\\library.md` so the plain-text
view stays current without a separate export step.
"""
import re
import sqlite3
import threading
from datetime import datetime
from pathlib import Path

EXPORT_BANNER = "> Generated by `arti-lit library export` -- do not hand-edit, changes will be overwritten."

_lock = threading.Lock()

SCHEMA = """
CREATE TABLE IF NOT EXISTS sources (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,
  key          TEXT NOT NULL UNIQUE,
  citation     TEXT NOT NULL,
  doi          TEXT,
  local_file   TEXT,
  read_status  TEXT NOT NULL DEFAULT 'export-only',
  used_in      TEXT,
  created_at   TEXT NOT NULL,
  updated_at   TEXT NOT NULL
);
"""

READ_STATUSES = ("export-only", "abstract", "fulltext", "read")


def _now():
    return datetime.now().isoformat(timespec="seconds")


def _paths(project):
    root = Path(project).resolve() if project else Path.cwd()
    return {
        "root": root,
        "db": root / "literature" / "arti-lit.db",
        "legacy_library": root / "literature" / "library.md",
    }


def _connect(db_path):
    db_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(db_path, timeout=5)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA busy_timeout=5000")
    return conn


def _row_to_dict(row):
    return dict(row) if row is not None else None


def init_db(project=None):
    """Creates the schema (idempotent) and, the first time arti-lit.db does
    not exist yet, one-time imports literature\\library.md. The markdown file
    is left in place -- it becomes a generated export afterward, not
    deleted."""
    paths = _paths(project)
    is_new = not paths["db"].exists()
    with _lock:
        conn = _connect(paths["db"])
        try:
            conn.executescript(SCHEMA)
            conn.commit()
            if is_new:
                _migrate_legacy(conn, paths["legacy_library"])
                conn.commit()
        finally:
            conn.close()
    if is_new:
        library_export(project)
    return paths


def _migrate_legacy(conn, legacy_path):
    if not legacy_path.exists():
        return
    for row in _parse_library_md(legacy_path):
        try:
            now = _now()
            conn.execute(
                "INSERT OR IGNORE INTO sources "
                "(key, citation, doi, local_file, read_status, used_in, created_at, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (row["key"], row["citation"], row["doi"], row["local_file"],
                 row["read_status"], row["used_in"], now, now),
            )
        except Exception as e:
            print(f"warning: skipped library row {row!r}: {e}", file=_stderr())


def _stderr():
    import sys
    return sys.stderr


def _parse_library_md(path):
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 6:
            continue
        if cells[0].lower().startswith("key"):
            continue
        if all(re.fullmatch(r":?-+:?", c) for c in cells):
            continue
        rows.append({
            "key": cells[0],
            "citation": cells[1],
            "doi": cells[2] if cells[2] not in ("", "—") else None,
            "local_file": cells[3] if cells[3] not in ("", "—") else None,
            "read_status": cells[4] if cells[4] else "export-only",
            "used_in": cells[5] if cells[5] not in ("", "—") else None,
        })
    return rows



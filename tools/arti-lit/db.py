def library_add(project, key, citation, doi=None, local_file=None,
                 read_status="export-only", used_in=None):
    paths = _paths(project)
    with _lock:
        conn = _connect(paths["db"])
        try:
            if doi:
                dupe = conn.execute(
                    "SELECT key FROM sources WHERE doi = ? AND doi IS NOT NULL AND key != ?",
                    (doi, key),
                ).fetchone()
                if dupe is not None:
                    raise ValueError(
                        f"DOI {doi!r} already exists on key {dupe['key']!r} -- dedupe instead of adding"
                    )
            now = _now()
            conn.execute(
                "INSERT INTO sources (key, citation, doi, local_file, read_status, used_in, created_at, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (key, citation, doi, local_file, read_status, used_in, now, now),
            )
            conn.commit()
            row = _row_to_dict(conn.execute("SELECT * FROM sources WHERE key = ?", (key,)).fetchone())
        finally:
            conn.close()
    library_export(project)
    return row


def library_update(project, key, citation=None, doi=None, local_file=None,
                    read_status=None, used_in=None):
    paths = _paths(project)
    with _lock:
        conn = _connect(paths["db"])
        try:
            row = conn.execute("SELECT * FROM sources WHERE key = ?", (key,)).fetchone()
            if row is None:
                raise ValueError(f"no source with key {key!r}")
            entry = _row_to_dict(row)
            if doi:
                dupe = conn.execute(
                    "SELECT key FROM sources WHERE doi = ? AND doi IS NOT NULL AND key != ?",
                    (doi, key),
                ).fetchone()
                if dupe is not None:
                    raise ValueError(
                        f"DOI {doi!r} already exists on key {dupe['key']!r} -- dedupe instead of updating"
                    )
            new_citation = citation if citation is not None else entry["citation"]
            new_doi = doi if doi is not None else entry["doi"]
            new_local_file = local_file if local_file is not None else entry["local_file"]
            new_read_status = read_status if read_status is not None else entry["read_status"]
            new_used_in = used_in if used_in is not None else entry["used_in"]
            conn.execute(
                "UPDATE sources SET citation=?, doi=?, local_file=?, read_status=?, used_in=?, updated_at=? "
                "WHERE key=?",
                (new_citation, new_doi, new_local_file, new_read_status, new_used_in, _now(), key),
            )
            conn.commit()
            result = _row_to_dict(conn.execute("SELECT * FROM sources WHERE key = ?", (key,)).fetchone())
        finally:
            conn.close()
    library_export(project)
    return result


def library_get(project, key):
    paths = _paths(project)
    with _lock:
        conn = _connect(paths["db"])
        try:
            return _row_to_dict(conn.execute("SELECT * FROM sources WHERE key = ?", (key,)).fetchone())
        finally:
            conn.close()


def library_list(project, status=None):
    paths = _paths(project)
    with _lock:
        conn = _connect(paths["db"])
        try:
            if status:
                rows = conn.execute(
                    "SELECT * FROM sources WHERE read_status = ? ORDER BY key", (status,)
                ).fetchall()
            else:
                rows = conn.execute("SELECT * FROM sources ORDER BY key").fetchall()
            return [_row_to_dict(r) for r in rows]
        finally:
            conn.close()


def library_search(project, keywords):
    paths = _paths(project)
    like_terms = [f"%{k}%" for k in keywords]
    with _lock:
        conn = _connect(paths["db"])
        try:
            clauses = []
            params = []
            for term in like_terms:
                clauses.append("(citation LIKE ? OR key LIKE ? OR used_in LIKE ?)")
                params.extend([term, term, term])
            query = "SELECT * FROM sources"
            if clauses:
                query += " WHERE " + " AND ".join(clauses)
            query += " ORDER BY key"
            rows = conn.execute(query, params).fetchall()
            return [_row_to_dict(r) for r in rows]
        finally:
            conn.close()


def library_remove(project, key):
    paths = _paths(project)
    with _lock:
        conn = _connect(paths["db"])
        try:
            row = conn.execute("SELECT * FROM sources WHERE key = ?", (key,)).fetchone()
            conn.execute("DELETE FROM sources WHERE key = ?", (key,))
            conn.commit()
            result = _row_to_dict(row)
        finally:
            conn.close()
    library_export(project)
    return result


def library_export(project=None):
    paths = _paths(project)
    with _lock:
        conn = _connect(paths["db"])
        try:
            rows = conn.execute("SELECT * FROM sources ORDER BY key").fetchall()
            rows = [_row_to_dict(r) for r in rows]
        finally:
            conn.close()

    lines = [
        "# Literature Library",
        "",
        "**File location:** `literature\\library.md` — canonical bibliography, one source per line,",
        "superset including screened-out sources. See ARTi-writing's Reference System (Layer 2).",
        "",
        EXPORT_BANNER,
        "",
        "---",
        "",
        "| key | citation | DOI | local file | read-status | used-in |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['key']} | {r['citation']} | {r['doi'] or '—'} | {r['local_file'] or '—'} "
            f"| {r['read_status']} | {r['used_in'] or '—'} |"
        )
    paths["legacy_library"].parent.mkdir(parents=True, exist_ok=True)
    paths["legacy_library"].write_text("\n".join(lines) + "\n", encoding="utf-8")



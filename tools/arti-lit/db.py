_KEY_RE = re.compile(r"^(.*?)-(\d{4})([a-z]?)$")


def _key_sort_tuple(key):
    m = _KEY_RE.match(key)
    if not m:
        return (key, "", "")
    author, year, suffix = m.groups()
    return (author.lower(), year, suffix)


def refs_generate(project, keys, order="alpha", output=None):
    paths = _paths(project)
    seen = set()
    ordered_keys = []
    for k in keys:
        if k not in seen:
            seen.add(k)
            ordered_keys.append(k)

    with _lock:
        conn = _connect(paths["db"])
        try:
            rows_by_key = {}
            for k in ordered_keys:
                row = conn.execute("SELECT * FROM sources WHERE key = ?", (k,)).fetchone()
                if row is not None:
                    rows_by_key[k] = _row_to_dict(row)
        finally:
            conn.close()

    unresolved = [k for k in ordered_keys if k not in rows_by_key]
    resolved_keys = [k for k in ordered_keys if k in rows_by_key]
    if order == "alpha":
        resolved_keys = sorted(resolved_keys, key=_key_sort_tuple)
    elif order != "appearance":
        raise ValueError(f"unknown order {order!r} -- must be 'alpha' or 'appearance'")

    out_path = Path(output).resolve() if output else paths["root"] / "writing" / "references.md"
    lines = [
        "# References",
        "",
        EXPORT_BANNER.replace("library export", "refs generate"),
        "",
    ]
    for i, k in enumerate(resolved_keys, start=1):
        lines.append(f"{i}. {rows_by_key[k]['citation']}")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    return {"written": len(resolved_keys), "unresolved": unresolved, "output": str(out_path)}

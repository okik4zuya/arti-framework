def project_export():
    with _lock:
        conn = _connect()
        try:
            rows = conn.execute("SELECT * FROM project_index ORDER BY topic").fetchall()
            rows = [_row_to_dict(r) for r in rows]
        finally:
            conn.close()

    lines = [
        "# Idea/Paper Project Index",
        "",
        "**File location:** `~/.arti/memory/project-index.md` — one row per project folder, so the",
        "researcher can see everything in flight without opening each project individually.",
        "",
        EXPORT_BANNER,
        "",
        "> Claude upserts a project's row at **phase boundaries only** — project scaffolded, idea",
        "> complete (handoff written), writing started, submitted, published. Not once per stage: rewriting",
        "> this file five times during idea development costs more upkeep than the overview is worth. The",
        "> dashboard (`~/.arti/dashboard/`) reads and writes this same `project_index` table directly for",
        "> its own launcher fields (category/tags/lifecycle) — this markdown export covers every row.",
        "",
        "---",
        "",
        "| Topic / idea label | Project folder path | Current stage | Target journal | Status | Summary | Last updated |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['topic']} | {r['project_path']} | {r['stage']} | {r['target_journal'] or '—'} "
            f"| {r['status'] or ''} | {r['summary'] or '—'} | {r['updated_at']} |"
        )
    LEGACY_PROJECT_INDEX_PATH.parent.mkdir(parents=True, exist_ok=True)
    LEGACY_PROJECT_INDEX_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")



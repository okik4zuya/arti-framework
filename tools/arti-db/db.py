def project_upsert(project_path, topic, stage=None, target_journal=None, status=None, summary=None, updated=None):
    updated = updated or _today()
    with _lock:
        conn = _connect()
        try:
            row = conn.execute(
                "SELECT * FROM project_index WHERE project_path = ?", (project_path,)
            ).fetchone()
            now = _now()
            if row is None:
                conn.execute(
                    "INSERT INTO project_index (topic, project_path, stage, target_journal, status, summary, updated_at, created_at) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                    (topic, project_path, stage or "Not started", target_journal, status, summary, updated, now),
                )
            else:
                entry = _row_to_dict(row)
                new_stage = stage if stage is not None else entry["stage"]
                new_journal = target_journal if target_journal is not None else entry["target_journal"]
                new_status = status if status is not None else entry["status"]
                new_summary = summary if summary is not None else entry["summary"]
                conn.execute(
                    "UPDATE project_index SET topic=?, stage=?, target_journal=?, status=?, summary=?, updated_at=? "
                    "WHERE project_path=?",
                    (topic, new_stage, new_journal, new_status, new_summary, updated, project_path),
                )
            conn.commit()
            result = _row_to_dict(
                conn.execute("SELECT * FROM project_index WHERE project_path = ?", (project_path,)).fetchone()
            )
        finally:
            conn.close()
    project_export()
    return result


def project_list(stage=None, status=None):
    with _lock:
        conn = _connect()
        try:
            query = "SELECT * FROM project_index WHERE 1=1"
            params = []
            if stage:
                query += " AND stage = ?"
                params.append(stage)
            if status:
                query += " AND status = ?"
                params.append(status)
            query += " ORDER BY topic"
            rows = conn.execute(query, params).fetchall()
            return [_row_to_dict(r) for r in rows]
        finally:
            conn.close()



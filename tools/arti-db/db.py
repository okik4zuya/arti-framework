def idea_index_upsert(project, file, tipe="Ide", status=None, hook=None, used_in=None, date_added=None):
    date_added = date_added or _today()
    now = _now()
    with _lock:
        conn = _connect()
        try:
            row = conn.execute(
                "SELECT * FROM idea_index WHERE project = ? AND file = ?", (project, file)
            ).fetchone()
            if row is None:
                conn.execute(
                    "INSERT INTO idea_index (project, file, tipe, status, hook, used_in, date_added, "
                    "archived, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?, ?)",
                    (project, file, tipe, status, hook, used_in, date_added, now, now),
                )
            else:
                entry = _row_to_dict(row)
                conn.execute(
                    "UPDATE idea_index SET tipe=?, status=?, hook=?, used_in=?, date_added=?, updated_at=? "
                    "WHERE project=? AND file=?",
                    (tipe or entry["tipe"], status if status is not None else entry["status"],
                     hook if hook is not None else entry["hook"],
                     used_in if used_in is not None else entry["used_in"],
                     date_added, now, project, file),
                )
            conn.commit()
            result = _row_to_dict(
                conn.execute(
                    "SELECT * FROM idea_index WHERE project = ? AND file = ?", (project, file)
                ).fetchone()
            )
        finally:
            conn.close()
    idea_index_export()
    return result


def idea_index_list(project=None, status=None, include_archived=False):
    with _lock:
        conn = _connect()
        try:
            query = "SELECT * FROM idea_index WHERE 1=1"
            params = []
            if not include_archived:
                query += " AND archived = 0"
            if project:
                query += " AND project = ?"
                params.append(project)
            if status:
                query += " AND status = ?"
                params.append(status)
            query += " ORDER BY date_added"
            rows = conn.execute(query, params).fetchall()
            return [_row_to_dict(r) for r in rows]
        finally:
            conn.close()


def idea_index_archive(ids, summary):
    now = _now()
    with _lock:
        conn = _connect()
        try:
            conn.executemany(
                "UPDATE idea_index SET archived = 1, updated_at = ? WHERE id = ?",
                [(now, i) for i in ids],
            )
            conn.execute(
                "INSERT INTO idea_index_log (ts, note) VALUES (?, ?)", (now, summary)
            )
            conn.commit()
            rows = conn.execute(
                f"SELECT * FROM idea_index WHERE id IN ({','.join('?' * len(ids))})", ids
            ).fetchall()
            result = [_row_to_dict(r) for r in rows]
        finally:
            conn.close()
    idea_index_export()
    return result


def idea_index_log(note):
    now = _now()
    with _lock:
        conn = _connect()
        try:
            cur = conn.execute(
                "INSERT INTO idea_index_log (ts, note) VALUES (?, ?)", (now, note)
            )
            conn.commit()
            row = _row_to_dict(
                conn.execute("SELECT * FROM idea_index_log WHERE id = ?", (cur.lastrowid,)).fetchone()
            )
        finally:
            conn.close()
    idea_index_export()
    return row


def idea_index_export():
    with _lock:
        conn = _connect()
        try:
            rows = conn.execute(
                "SELECT * FROM idea_index WHERE archived = 0 ORDER BY date_added"
            ).fetchall()
            rows = [_row_to_dict(r) for r in rows]
            log_rows = conn.execute(
                "SELECT * FROM idea_index_log ORDER BY ts DESC"
            ).fetchall()
            log_rows = [_row_to_dict(r) for r in log_rows]
        finally:
            conn.close()

    lines = [
        "# Idea List Index",
        "",
        "**File location:** `~/.arti/inbox/idea-index.md` — a `project-index.md`-style aggregator: one row",
        "per raw idea captured in any project's `inbox/` folder (this project's own `inbox/` included), so",
        "\"what's my idea list and status\" is answered by reading this one file, no per-project scanning",
        "needed.",
        "",
        EXPORT_BANNER,
        "",
        "> Distinct from `~/.arti/inbox/index.md` (scoped to ideas about the ARTi framework/skills",
        "> themselves) and from `~/.arti/memory/research-idea-bank.md` (scoped to research/paper-topic",
        "> ideas parked from the Idea Canvas). This file covers everything captured via the `inbox/`",
        "> convention, across every kind of idea and every project.",
        "",
        "> Claude upserts a row here the moment an idea is triaged (OK/SKIP/PARKED) in any project's",
        "> `inbox/index.md` — the same touch-point pattern `project-index.md` already uses for paper-stage",
        "> upserts.",
        "",
        "---",
        "",
        "| Project | File | Tipe | Status | One-line hook | Dipakai di | Date added |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['project']} | {r['file']} | {r['tipe']} | {r['status'] or '(untriaged)'} "
            f"| {r['hook'] or ''} | {r['used_in'] or '—'} | {r['date_added']} |"
        )
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Change log")
    for lr in log_rows:
        lines.append(f"- {lr['ts']} — {lr['note']}")
    LEGACY_IDEA_INDEX_PATH.parent.mkdir(parents=True, exist_ok=True)
    LEGACY_IDEA_INDEX_PATH.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")

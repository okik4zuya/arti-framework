def idea_bank_add(label, idea_text, c=None, m=None, e=None, novelty_label=None,
                   date_parked=None, source_project=None, reason_parked=None, notes=None, tag=None):
    date_parked = date_parked or _today()
    now = _now()
    with _lock:
        conn = _connect()
        try:
            cur = conn.execute(
                "INSERT INTO idea_bank (label, idea_text, novelty_c, novelty_m, novelty_e, "
                "novelty_label, date_parked, source_project, reason_parked, notes, tag, created_at, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (label, idea_text, c, m, e, novelty_label, date_parked, source_project,
                 reason_parked, notes, tag, now, now),
            )
            conn.commit()
            row = _row_to_dict(
                conn.execute("SELECT * FROM idea_bank WHERE id = ?", (cur.lastrowid,)).fetchone()
            )
        finally:
            conn.close()
    idea_bank_export()
    return row


def idea_bank_search(keywords):
    like_terms = [f"%{k}%" for k in keywords]
    with _lock:
        conn = _connect()
        try:
            clauses = []
            params = []
            for term in like_terms:
                clauses.append(
                    "(idea_text LIKE ? OR label LIKE ? OR source_project LIKE ? OR notes LIKE ?)"
                )
                params.extend([term, term, term, term])
            query = "SELECT * FROM idea_bank"
            if clauses:
                query += " WHERE " + " AND ".join(clauses)
            query += " ORDER BY date_parked DESC"
            rows = conn.execute(query, params).fetchall()
            return [_row_to_dict(r) for r in rows]
        finally:
            conn.close()


